// Small hand-authored pixel-art icons for button labels (<=10x10), used in
// place of text for the Focus/Feed actions. Colors are mostly TinyScreen's
// own named 8-bit constants (TS_8b_*) rather than custom RGB values
// quantized down -- this format only gives the red channel 2 bits, so an
// arbitrary custom color comes out muddy; the library's presets are chosen
// to stay vivid within that format. `kInkColor` (see colors.h) is the one
// custom color, used for outlines/frames that need to read against the
// white background below.
//
// Background is white (TS_8b_White) rather than baked-transparent: the
// hourglass's frame and the pizza's diagonal edge used to be plain white
// against a black/cream background, which would vanish here, so those were
// recolored to kInkColor.
